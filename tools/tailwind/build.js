// Usage:  cd tools/tailwind && npm install && npm run build
// Scans ../../index.html for tw-* classes, builds minified CSS and splices it
// between the TW-HOME markers inside index.html.
const { execFileSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const html = path.resolve(__dirname, '../../index.html');
const bin = path.resolve(__dirname, 'node_modules/.bin/tailwindcss');
const css = execFileSync(bin, ['-c', path.join(__dirname, 'tailwind.config.js'),
  '-i', path.join(__dirname, 'input.css'), '--minify'], { cwd: __dirname, encoding: 'utf8' }).trim();

const START = '/* TW-HOME:START (generated by tools/tailwind/build.js, do not edit by hand) */';
const END = '/* TW-HOME:END */';
let src = fs.readFileSync(html, 'utf8');
const a = src.indexOf(START), b = src.indexOf(END);
if (a === -1 || b === -1) throw new Error('TW-HOME markers not found in index.html');
src = src.slice(0, a) + START + '\n' + css + '\n' + src.slice(b);
fs.writeFileSync(html, src);
console.log('Tailwind CSS inlined: ' + css.length + ' bytes');
